import { describe, it, expect } from "vitest";
import { decomposeSceneDescription } from "../sceneDecomposer";

describe("sceneDecomposer (Task PR-12)", () => {
  it("should decompose user scene description into structured manifest and stage prompts", () => {
    const manifest = decomposeSceneDescription(
      "Ruby seated at mahogany desk in amber newsroom broadcast studio wearing dark navy blazer holding whiskey glass"
    );

    expect(manifest.primaryPersona.personaKey).toBe("ruby");
    expect(manifest.environmentTags.length).toBeGreaterThan(0);
    expect(manifest.props).toContain("mahogany news anchor desk");
    expect(manifest.wardrobeDescription).toContain("blazer");
    expect(manifest.autoGeneratedStagePrompts.stage1Environment).toContain("studio");
    expect(manifest.autoGeneratedStagePrompts.stage3Persona).toContain("female news anchor");
  });
});
