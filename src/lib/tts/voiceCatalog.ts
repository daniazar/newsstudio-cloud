export function getSpanishRioplatensePersonas(): DualTierVoiceProfile[] {
  return DUAL_TIER_VOICE_PROFILES.filter((p) =>
    p.locale === "es_AR" || p.locale === "es_UY" || p.locale === "es_PY"
  );
}

/**
 * Returns all English language personas (en_US, en_GB).
 */
export function getEnglishPersonas(): DualTierVoiceProfile[] {
  return DUAL_TIER_VOICE_PROFILES.filter((p) => p.language === "en");
}

/**
 * Returns personas filtered by specific locale.
 */
export function getPersonasByLocale(locale: string): DualTierVoiceProfile[] {
  return DUAL_TIER_VOICE_PROFILES.filter((p) => p.locale.toLowerCase() === locale.toLowerCase());
}

/**
 * Computes benchmark aggregate statistics across the entire 48-persona roster.
 */
export function getBenchmarkSummary(): {
  avgMos: number;
  avgRtfTier1: number;
  avgRtfTier2: number;
  avgPhoneticAccuracy: number;
  avgFinancialAccuracy: number;
  totalPersonas: number;
} {
  const total = DUAL_TIER_VOICE_PROFILES.length;
  if (total === 0) {
    return {
      avgMos: 0,
      avgRtfTier1: 0,
      avgRtfTier2: 0,
      avgPhoneticAccuracy: 0,
      avgFinancialAccuracy: 0,
      totalPersonas: 0,
    };
  }

  const sum = DUAL_TIER_VOICE_PROFILES.reduce(
    (acc, p) => ({
      mos: acc.mos + p.benchmarks.mos,
      rtfTier1: acc.rtfTier1 + p.benchmarks.rtfTier1,
      rtfTier2: acc.rtfTier2 + p.benchmarks.rtfTier2,
      phonetic: acc.phonetic + p.benchmarks.phoneticAccuracy,
      financial: acc.financial + p.benchmarks.financialTickersAccuracy,
    }),
    { mos: 0, rtfTier1: 0, rtfTier2: 0, phonetic: 0, financial: 0 }
  );

  return {
    avgMos: Number((sum.mos / total).toFixed(2)),
    avgRtfTier1: Number((sum.rtfTier1 / total).toFixed(3)),
    avgRtfTier2: Number((sum.rtfTier2 / total).toFixed(2)),
    avgPhoneticAccuracy: Number((sum.phonetic / total).toFixed(1)),
    avgFinancialAccuracy: Number((sum.financial / total).toFixed(1)),
    totalPersonas: total,
  };
}

/**
 * Resolves ModernTtsOptions configured for the given persona and tier.
 */
export function resolveDualTierVoiceOptions(
  personaId: string,
  tier: VoiceTier = "tier1",
  overrides: Partial<ModernTtsOptions> = {}
): ModernTtsOptions {
  const profile = getVoiceProfileByPersonaId(personaId);
  const isFast = tier === "tier1" || tier === "fast";

  if (!profile) {
    return {
      engine: isFast ? "piper" : "f5_tts",
      personaId,
      ...overrides,
    };
  }

  if (isFast) {
    return {
      engine: "piper",
      personaId: profile.personaId,
      checkpoint: profile.tier1.model,
      pitchShift: profile.tier1.pitchShift,
      speedFactor: profile.tier1.speedFactor,
      language: profile.locale.startsWith("es") ? "es" : profile.language,
      cadencePreset: profile.recommendedCadence,
      applyYeismo: profile.locale === "es_AR" || profile.locale === "es_UY",
      ...overrides,
    };
  }

  return {
    engine: profile.tier2.engine,
    personaId: profile.personaId,
    checkpoint: profile.tier2.checkpoint,
    pitchShift: profile.tier2.pitchShift,
    speedFactor: profile.tier2.speedFactor,
    language: profile.locale.startsWith("es") ? "es" : profile.language,
    cadencePreset: profile.recommendedCadence,
    applyYeismo: profile.locale === "es_AR" || profile.locale === "es_UY",
    ...overrides,
  };
}

/**
 * Synthesizes audio using the Dual-Tier Voice Vault architecture.
 */
export async function generateDualTierAudio(
  text: string,
  personaId: string,
  tier: VoiceTier = "tier1",
  overrides: Partial<ModernTtsOptions> = {}
): Promise<ModernTtsBuffer> {
  const profile = getVoiceProfileByPersonaId(personaId);
  const options = resolveDualTierVoiceOptions(personaId, tier, overrides);
  const referenceAudio = (tier === "tier2" || tier === "studio") ? (profile?.tier2.referenceAudio || "") : "";

  const { generateAudioWithModernTts } = await import("./modernTtsClient");
  return generateAudioWithModernTts(text, referenceAudio, options);
}
